/* Rebuild the city menus after changing the standalone Exchange, its artwork or its styles:
 *   node tools/bundle-exchange.cjs
 *   node tools/bundle-exchange.cjs --check
 */
const fs = require('node:fs');
const path = require('node:path');
const projectCrateWallet = require('./project-crate-wallet.cjs');

const root = path.resolve(__dirname, '..');
const output = path.join(root, 'exchange-room.js');
const read = ref => fs.readFileSync(path.join(root, ref.split('?')[0]), 'utf8');
const mime = {'.woff2':'font/woff2', '.png':'image/png'};

function dataURL(filename) {
  const type = mime[path.extname(filename)];
  if (!type) throw new Error('Unsupported embedded asset: ' + filename);
  return 'data:' + type + ';base64,' + fs.readFileSync(filename).toString('base64');
}

function inlineStylesheet(ref) {
  const directory = path.dirname(path.join(root, ref));
  const css = read(ref).replace(/url\((['"]?)([^'")]+)\1\)/g, (match, quote, asset) => {
    if (asset.startsWith('data:')) return match;
    return "url('" + dataURL(path.resolve(directory, asset)) + "')";
  });
  return '<style>' + css + '</style>';
}

function connectCity() {
  window.BBCityRoom = window.frameElement.bbCityRoom;
  window.liveCityRelease = (action, command) => window.BBCityRoom.request(action, command);
  window.BBModels = {render: key => window.BBCityRoom.renderModel(key)};
  document.addEventListener('click', event => {
    const link = event.target.closest('a.city-close, #exchangeAccount a[href="./"], #exchangeAccount a[href="/staging/"]');
    if (link) {
      event.preventDefault();
      if (window.BBCityRoom.isActive()) window.BBCityRoom.close();
    }
  });
  document.addEventListener('keydown', event => {
    if (event.key !== 'Escape') return;
    event.preventDefault();
    const modal = document.querySelector('#modalRoot');
    if (modal?.childElementCount) {
      modal.querySelector('[data-action="close-modal"]')?.click();
    } else if (window.BBCityRoom.isActive()) {
      window.BBCityRoom.close();
    }
  });
}

const sprites = {};
for (const tier of ['silver', 'gold', 'emerald', 'ruby', 'diamond']) {
  sprites[tier] = dataURL(path.join(root, 'exchange-art', tier + '.png'));
}
let html = read('banksia-exchange.html');
html = html.replace(/<link rel="preload" as="font"[^>]*>/g, '');
html = html.replace(/<link rel="stylesheet" href="([^"]+)">/g, (_, ref) => inlineStylesheet(ref));
// The city dialog already takes the device's safe area out of the frame's viewport.
html = html.replace('</head>', '<style>:root { --safe-top:0px; --safe-right:0px; --safe-bottom:0px; --safe-left:0px; }</style></head>');
html = html.replace(/<script src="([^"]+)"><\/script>/g, (_, ref) => {
  const script = ref.split('?')[0] === './release-account.js'
    ? '(' + connectCity.toString() + ')();\nconst cityCrateSprites = ' + JSON.stringify(sprites) + ';\n' + read('dosh-shop-schedule.js')
    : read(ref);
  return '<script>' + script + '</script>';
});

// The standalone room loads its account controller only in the Crates view.
// Keep the same timing, while reading the code from the installed game.
const controller = /accountScript\.src\s*=\s*'([^']*exchange-account\.js[^']*)';/;
if (!controller.test(html)) throw new Error('Exchange account script entry not found');
html = html.replace(controller, (_, ref) => 'accountScript.text = ' +
  JSON.stringify(read(ref).replaceAll('new URLSearchParams(location.search)', 'new URLSearchParams(window.BBCityRoom.query)'))
    .replaceAll('<', '\\u003c') + ';');

const sprite = /src="exchange-art\/\$\{tier\}\.png[^"]*"/;
if (!sprite.test(html)) throw new Error('Crate sprite entry not found');
html = html.replace(sprite, 'src="${cityCrateSprites[tier]}"');
html = html.replaceAll('new URLSearchParams(location.search)', 'new URLSearchParams(window.BBCityRoom.query)');

// A template literal keeps the generated markup readable in developer tools.
const literal = html.replaceAll('\\', '\\\\').replaceAll('`', '\\`').replaceAll('${', '\\${');
const content = '// Generated by tools/bundle-exchange.cjs from banksia-exchange.html and its dependencies.\n' +
  'window.BBProjectedCrateWallet = ' + projectCrateWallet.toString() + ';\n' +
  'window.BBExchangeDocument = `' + literal + '`;\n';
if (process.argv.includes('--check')) {
  if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== content) {
    throw new Error('Run node tools/bundle-exchange.cjs to update exchange-room.js');
  }
} else {
  fs.writeFileSync(output, content);
}
